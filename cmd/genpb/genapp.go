// app 侧生成物（logic 脚手架、注册表）的推导规则：
//
//	proto/<app>/<name>.proto    →  app/<app>/logic/<name>/msg_<name>.go  脚手架，只建不覆盖
//	                            →  app/<app>/processor_registry.gen.go   注册表，全量重写
//
// app 名取 proto 目录名，logic 包名取 proto 文件 basename。名字对不上就生成到
// 别处，所以这两条约定必须守住。
//
// 协议类型不再包一层：protocol_types.go 给 pb 类型加了 TypeId 方法，处理函数直接收 *testpb.X。
// 处理方式（认证、事务、锁）是处理函数 session 参数的类型，生成器不需要知道。

// protoFile 一个 app proto 文件生成所需的一切。
type protoFile struct {
	Path         string // test/red_envelope.proto
	App          string // test
	LogicPackage string // red_envelope
	GoImportPath string // go_pg_test/genpb/test
	GoPackage    string // testpb
	Module       string // go_pg_test
	Messages     []*protoMsg
}

// ClientMessages 需要业务处理函数的消息，约定客户端协议以 C 开头。
func (f *protoFile) ClientMessages() []*protoMsg {
	var out []*protoMsg
	for _, m := range f.Messages {
		if strings.HasPrefix(m.Name, "C") {
			out = append(out, m)
		}
	}
	return out
}

// SessionImportPath 这个 app 的 session 包 import 路径：处理方式的类型（session.User 等）在里面。
func (f *protoFile) SessionImportPath() string {
	return fmt.Sprintf("%s/app/%s/session", f.Module, f.App)
}

type protoMsg struct {
	Name   string
	TypeId int32
}

// collectAppProtoFiles 挑出属于某个 app 的 proto 文件。
//
// 只认 proto/<app>/<name>.proto 这种带目录的——顶层的共享 proto（ext.proto）
// 不算 app 协议。同时要求 go_package 在本 module 下，这样 desc.pb 里
// --include_imports 带进来的 google/protobuf/*.proto 会被自然滤掉。
func collectAppProtoFiles(files *protoregistry.Files, module string, typeIDExtType protoreflect.ExtensionType) ([]*protoFile, error) {
	var out []*protoFile
	var fail error

	files.RangeFiles(func(fd protoreflect.FileDescriptor) bool {
		app, logicPackage, ok := appProtoPath(fd.Path())
		if !ok {
			return true
		}
		if !strings.HasPrefix(fd.Options().(*descriptorpb.FileOptions).GetGoPackage(), module+"/") {
			return true
		}
		goImportPath, goPackage, err := goPackageOf(fd)
		if err != nil {
			fail = err
			return false
		}

		pf := &protoFile{
			Path:         fd.Path(),
			App:          app,
			LogicPackage: logicPackage,
			GoImportPath: goImportPath,
			GoPackage:    goPackage,
			Module:       module,
		}

		messages := fd.Messages()
		for i := range messages.Len() {
			msg := messages.Get(i)
			opts := msg.Options()
			if opts == nil || !hasTypeId(opts, typeIDExtType) {
				continue
			}

			pf.Messages = append(pf.Messages, &protoMsg{
				Name:   string(msg.Name()),
				TypeId: proto.GetExtension(opts, typeIDExtType).(int32),
			})
		}

		if len(pf.Messages) > 0 {
			out = append(out, pf)
		}
		return true
	})
	if fail != nil {
		return nil, fail
	}

	slices.SortStableFunc(out, func(a, b *protoFile) int {
		return cmp.Compare(a.Path, b.Path)
	})
	return out, nil
}

// appProtoPath 从 proto 路径拆出 app 名和 logic 包名。
// 只认两级及以上的路径，顶层的 ext.proto 返回 false。
func appProtoPath(path string) (app, logicPackage string, ok bool) {
	app, file, found := strings.Cut(path, "/")
	if !found || app == "" {
		return "", "", false
	}
	base, found := strings.CutSuffix(filepath.Base(file), ".proto")
	if !found || base == "" {
		return "", "", false
	}
	return app, base, true
}

// genAppCode 生成 app 侧的 logic 脚手架和注册表。
// 只渲染进内存，不落盘——调用方在全部生成步骤成功后才统一发布。
func genAppCode(repoRoot, module string, protos []*protoFile) ([]generatedFile, error) {
	var out []generatedFile
	for _, pf := range protos {
		stub, err := genLogicStub(repoRoot, pf)
		if err != nil {
			return nil, err
		}
		if stub != nil {
			out = append(out, *stub)
		}
	}

	regs, err := genRegisters(repoRoot, module, protos)
	if err != nil {
		return nil, err
	}
	return append(out, regs...), nil
}

// stubData 渲染脚手架用：proto 文件的信息，加上这次要补的处理函数。
type stubData struct {
	*protoFile
	Missing []*protoMsg
}

// 处理函数的第二个参数是 session.User：默认的处理方式（验 loginToken + uid 锁事务 +
// requestToken 链）。要别的方式就改这个类型，比如只认证用 session.Auth，不用重新生成。
const logicStubTmpl = `// 只创建一次，之后归你改，genpb 不会覆盖这个文件。
// 处理方式由 session 参数的类型决定（见 {{.SessionImportPath}}），改类型就行。
// source: {{.Path}}

package {{.LogicPackage}}

import (
	"context"

	"{{.SessionImportPath}}"
	{{.GoPackage}} "{{.GoImportPath}}"
)

{{range $msg := .Missing}}
func Process{{$msg.Name}}(ctx context.Context, s *session.User, req *{{$.GoPackage}}.{{$msg.Name}}) error {
	// TODO: 实现业务逻辑
	return nil
}
{{end}}`

const logicStubFragmentTmpl = `{{range $msg := .Missing}}
func Process{{$msg.Name}}(ctx context.Context, s *session.User, req *{{$.GoPackage}}.{{$msg.Name}}) error {
	// TODO: 实现业务逻辑
	return nil
}
{{end}}`

const registerTmpl = `// Code generated by genpb; DO NOT EDIT.
//
// 每个客户端协议（C 开头）一行。处理方式不在这里：它是处理函数 session 参数的类型
// （见 {{.SessionImportPath}}），改处理方式不用重新生成。
package main

import (
{{- range $imp := .LogicImports}}
	"{{$imp}}"
{{- end}}
)

func init() {
{{- range $e := .Entries}}
	processRegistry.Handle({{$e.LogicPackage}}.Process{{$e.Name}})
{{- end}}
}
`

// genRegisters 按 app 各生成一份注册表。
func genRegisters(repoRoot, module string, protos []*protoFile) ([]generatedFile, error) {
	var out []generatedFile
	byApp := map[string][]*protoFile{}
	for _, pf := range protos {
		byApp[pf.App] = append(byApp[pf.App], pf)
	}

	for _, app := range slices.Sorted(maps.Keys(byApp)) {
		byApp[app] = slices.DeleteFunc(byApp[app], func(pf *protoFile) bool {
			return len(pf.ClientMessages()) == 0
		})
		if len(byApp[app]) == 0 {
			continue
		}

		data := struct {
			SessionImportPath string
			LogicImports      []string
			Entries           []struct{ Name, LogicPackage string }
		}{
			SessionImportPath: byApp[app][0].SessionImportPath(),
		}

		for _, pf := range byApp[app] {
			data.LogicImports = append(data.LogicImports, fmt.Sprintf("%s/app/%s/logic/%s", module, app, pf.LogicPackage))
			for _, m := range pf.ClientMessages() {
				data.Entries = append(data.Entries, struct{ Name, LogicPackage string }{
					Name: m.Name, LogicPackage: pf.LogicPackage,
				})
			}
		}

		f, err := renderFile(filepath.Join(repoRoot, "app", app, "processor_registry.gen.go"), registerTmpl, data)
		if err != nil {
			return nil, err
		}
		out = append(out, f)
	}
	return out, nil
}

// renderFile 渲染模板、gofmt 一遍，结果留在内存里等统一发布。
func renderFile(path, tmpl string, data any) (generatedFile, error) {
	buf, err := render(tmpl, data)
	if err != nil {
		return generatedFile{}, fmt.Errorf("%s: %w", path, err)
	}
	return generatedFile{path: path, data: buf}, nil
}

// genLogicStub 保证每个客户端协议都有对应的 Process 函数。
//
// 处理函数可以写在 logic 包的任何一个文件里（比如 login.go），所以先看整个包缺哪些，
// 再决定建不建、补不补 msg_<name>.go：只看 msg_<name>.go 会把别处已有的函数再生成一份，
// 编译报重复定义。
//
// 文件不存在就建出来；已存在就在末尾补上缺的那些。两种情况下都只做加法——
// 里面是人写的业务逻辑。之所以要补而不是"文件在就跳过"，是因为协议是按 message
// 加的：文件一旦存在，之后新增的协议就永远拿不到脚手架，而生成的注册表已经
// 引用了它，编译直接断。
func genLogicStub(repoRoot string, pf *protoFile) (*generatedFile, error) {
	clients := pf.ClientMessages()
	if len(clients) == 0 {
		return nil, nil
	}

	dir := filepath.Join(repoRoot, "app", pf.App, "logic", pf.LogicPackage)
	have, err := declaredFuncs(dir)
	if err != nil {
		return nil, err
	}
	missing := slices.DeleteFunc(slices.Clone(clients), func(m *protoMsg) bool {
		return have["Process"+m.Name]
	})
	if len(missing) == 0 {
		return nil, nil
	}

	path := filepath.Join(dir, "msg_"+pf.LogicPackage+".go")
	data := stubData{protoFile: pf, Missing: missing}

	src, err := os.ReadFile(path)
	if errors.Is(err, fs.ErrNotExist) {
		f, err := renderFile(path, logicStubTmpl, data)
		if err != nil {
			return nil, err
		}
		log.Printf("%s: new stub, yours to maintain from here on", path)
		return &f, nil
	}
	if err != nil {
		return nil, err
	}

	f, err := parser.ParseFile(token.NewFileSet(), path, src, parser.ImportsOnly)
	if err != nil {
		return nil, fmt.Errorf("%s: cannot parse (mid-edit?); finish it and rerun the generator: %w", path, err)
	}

	// 追加的 stub 要用 context、session 和 pb 包。文件里没有就让人自己加——生成器不猜 import，
	// 猜错了会写出一份编译不过的文件，比直接报错难查。
	for _, need := range []string{"context", pf.SessionImportPath(), pf.GoImportPath} {
		if !hasImport(f, need) {
			return nil, fmt.Errorf("%s: missing import %q; add it and rerun the generator", path, need)
		}
	}

	var frag bytes.Buffer
	if err := template.Must(template.New("frag").Parse(logicStubFragmentTmpl)).Execute(&frag, data); err != nil {
		return nil, err
	}

	// 整份过一遍 gofmt：人写的那部分本来就是格式化过的，等于没动；
	// 追加的部分则保证格式正确。过不了说明拼出来的不是合法 Go，不写。
	merged, err := format.Source(append(slices.Clone(src), frag.Bytes()...))
	if err != nil {
		return nil, fmt.Errorf("%s: result after top-up is not valid Go, nothing written: %w", path, err)
	}

	names := make([]string, 0, len(missing))
	for _, m := range missing {
		names = append(names, "Process"+m.Name)
	}
	log.Printf("%s: topped up %s", path, strings.Join(names, ", "))
	return &generatedFile{path: path, data: merged}, nil
}

// declaredFuncs 返回 dir 里（测试文件除外）所有包级函数的名字。目录不存在时返回空集。
func declaredFuncs(dir string) (map[string]bool, error) {
	entries, err := os.ReadDir(dir)
	if errors.Is(err, fs.ErrNotExist) {
		return map[string]bool{}, nil
	}
	if err != nil {
		return nil, err
	}

	have := map[string]bool{}
	fset := token.NewFileSet()
	for _, e := range entries {
		name := e.Name()
		if e.IsDir() || !strings.HasSuffix(name, ".go") || strings.HasSuffix(name, "_test.go") {
			continue
		}
		path := filepath.Join(dir, name)
		f, err := parser.ParseFile(fset, path, nil, parser.SkipObjectResolution)
		if err != nil {
			return nil, fmt.Errorf("%s: cannot parse (mid-edit?); finish it and rerun the generator: %w", path, err)
		}
		for _, d := range f.Decls {
			if fn, ok := d.(*ast.FuncDecl); ok && fn.Recv == nil {
				have[fn.Name.Name] = true
			}
		}
	}
	return have, nil
}

func hasImport(f *ast.File, path string) bool {
	for _, imp := range f.Imports {
		if s, err := strconv.Unquote(imp.Path.Value); err == nil && s == path {
			return true
		}
	}
	return false
}

// render 渲染模板并 gofmt。生成的东西必须能编译，格式不对就直接报错。
func render(tmpl string, data any) ([]byte, error) {
	t, err := template.New("gen").Parse(tmpl)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("generated code is not valid Go: %w\n---\n%s", err, buf.String())
	}
	return src, nil
}
