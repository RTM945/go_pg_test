// app 侧生成物（msg 包装类、logic 脚手架、注册表）的推导规则：
//
//	proto/<app>/<name>.proto    →  app/<app>/msg/<name>.go            包装类，全量重写
//	                            →  app/<app>/logic/<name>/msg_<name>.go  脚手架，只建不覆盖
//	                            →  app/<app>/processor_registry.gen.go   注册表，全量重写
//
// app 名取 proto 目录名，logic 包名取 proto 文件 basename。名字对不上就生成到
// 别处，所以这两条约定必须守住。

// protoFile 一个 app proto 文件生成所需的一切。
type protoFile struct {
	Path         string // test/red_envelope.proto
	App          string // test
	LogicPackage string // red_envelope
	GoImportPath string // go_pg_test/genpb/test
	GoPackage    string // testpb
	Module       string // go_pg_test
	Messages     []*protoMsg
}

// ClientMessages 需要业务处理函数的消息，约定客户端协议以 C 开头。
func (f *protoFile) ClientMessages() []*protoMsg {
	var out []*protoMsg
	for _, m := range f.Messages {
		if strings.HasPrefix(m.Name, "C") {
			out = append(out, m)
		}
	}
	return out
}

// MsgImportPath 这个 app 的 msg 包 import 路径。
func (f *protoFile) MsgImportPath() string {
	return fmt.Sprintf("%s/app/%s/msg", f.Module, f.App)
}

type protoMsg struct {
	Name   string
	TypeId int32
}

// collectAppProtoFiles 挑出属于某个 app 的 proto 文件。
//
// 只认 proto/<app>/<name>.proto 这种带目录的——顶层的共享 proto（ext.proto）
// 不算 app 协议。同时要求 go_package 在本 module 下，这样 desc.pb 里
// --include_imports 带进来的 google/protobuf/*.proto 会被自然滤掉。
func collectAppProtoFiles(files *protoregistry.Files, module string, typeIDExtType protoreflect.ExtensionType) ([]*protoFile, error) {
	var out []*protoFile
	var fail error

	files.RangeFiles(func(fd protoreflect.FileDescriptor) bool {
		app, logicPackage, ok := appProtoPath(fd.Path())
		if !ok {
			return true
		}
		if !strings.HasPrefix(fd.Options().(*descriptorpb.FileOptions).GetGoPackage(), module+"/") {
			return true
		}
		goImportPath, goPackage, err := goPackageOf(fd)
		if err != nil {
			fail = err
			return false
		}

		pf := &protoFile{
			Path:         fd.Path(),
			App:          app,
			LogicPackage: logicPackage,
			GoImportPath: goImportPath,
			GoPackage:    goPackage,
			Module:       module,
		}

		messages := fd.Messages()
		for i := 0; i < messages.Len(); i++ {
			msg := messages.Get(i)
			opts := msg.Options()
			if opts == nil || !proto.HasExtension(opts, typeIDExtType) {
				continue
			}

			pf.Messages = append(pf.Messages, &protoMsg{
				Name:   string(msg.Name()),
				TypeId: proto.GetExtension(opts, typeIDExtType).(int32),
			})
		}

		if len(pf.Messages) > 0 {
			out = append(out, pf)
		}
		return true
	})
	if fail != nil {
		return nil, fail
	}

	slices.SortStableFunc(out, func(a, b *protoFile) int {
		return cmp.Compare(a.Path, b.Path)
	})
	return out, nil
}

// appProtoPath 从 proto 路径拆出 app 名和 logic 包名。
// 只认两级及以上的路径，顶层的 ext.proto 返回 false。
func appProtoPath(path string) (app, logicPackage string, ok bool) {
	app, file, found := strings.Cut(path, "/")
	if !found || app == "" {
		return "", "", false
	}
	base, found := strings.CutSuffix(filepath.Base(file), ".proto")
	if !found || base == "" {
		return "", "", false
	}
	return app, base, true
}

// genAppCode 生成 app 侧的 msg 包装类、logic 脚手架和注册表。
func genAppCode(repoRoot, module string, protos []*protoFile) error {
	for _, pf := range protos {
		if err := writeGenerated(filepath.Join(repoRoot, "app", pf.App, "msg", pf.LogicPackage+".go"), msgWrapperTmpl, pf); err != nil {
			return err
		}
		if err := genLogicStub(filepath.Join(repoRoot, "app", pf.App, "logic", pf.LogicPackage, "msg_"+pf.LogicPackage+".go"), pf); err != nil {
			return err
		}
	}
	return genRegisters(repoRoot, module, protos)
}

const msgWrapperTmpl = `// Code generated by genpb; DO NOT EDIT.
// source: {{.Path}}

package msg

import (
	"go_pg_test/io"

	{{.GoPackage}} "{{.GoImportPath}}"
)

{{range $msg := .Messages}}
// {{$msg.Name}} 内嵌生成的 protobuf 类型，字段和 GetXxx 都直接可用，
// 不用为每个协议再写一遍字段访问器。
type {{$msg.Name}} struct {
	*{{$.GoPackage}}.{{$msg.Name}}

	session *io.Session
	typeId  int32
}

func New{{$msg.Name}}() *{{$msg.Name}} {
	return &{{$msg.Name}}{
		{{$msg.Name}}: &{{$.GoPackage}}.{{$msg.Name}}{},
		typeId:        {{$.GoPackage}}.PROTOCOL_TYPE_{{$msg.Name}},
	}
}

func (m *{{$msg.Name}}) SetSession(session *io.Session) {
	m.session = session
}

func (m *{{$msg.Name}}) Session() *io.Session {
	return m.session
}

func (m *{{$msg.Name}}) TypeId() int32 {
	return m.typeId
}

func (m *{{$msg.Name}}) Size() int {
	return m.{{$msg.Name}}.SizeVT()
}

func (m *{{$msg.Name}}) Read(buffer []byte) error {
	return m.{{$msg.Name}}.UnmarshalVT(buffer)
}

func (m *{{$msg.Name}}) Write(buffer []byte) (int, error) {
	return m.{{$msg.Name}}.MarshalToVT(buffer)
}
{{end}}`

