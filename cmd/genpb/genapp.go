const registerTmpl = `// Code generated by genpb; DO NOT EDIT.
//
// 这里只自动注册客户端协议（C 开头）。
package main

import (
{{- range $imp := .LogicImports}}
	"{{$imp}}"
{{- end}}
	"{{.MsgImportPath}}"
{{range $imp := .PbImports}}
	{{$imp.Package}} "{{$imp.Path}}"
{{- end}}
)

func init() {
{{- range $e := .Entries}}
	processRegistry.Register({{$e.GoPackage}}.PROTOCOL_TYPE_{{$e.Name}}, msg.New{{$e.Name}}, {{$e.LogicPackage}}.Process{{$e.Name}}, processUserTryLock)
{{- end}}
}
`

// genRegisters 按 app 各生成一份注册表。
func genRegisters(repoRoot, module string, protos []*protoFile) error {
	byApp := map[string][]*protoFile{}
	for _, pf := range protos {
		byApp[pf.App] = append(byApp[pf.App], pf)
	}

	for _, app := range slices.Sorted(maps.Keys(byApp)) {
		byApp[app] = slices.DeleteFunc(byApp[app], func(pf *protoFile) bool {
			return len(pf.ClientMessages()) == 0
		})
		if len(byApp[app]) == 0 {
			continue
		}

		data := struct {
			MsgImportPath string
			LogicImports  []string
			PbImports     []struct{ Path, Package string }
			Entries       []struct{ Name, GoPackage, LogicPackage string }
		}{
			MsgImportPath: fmt.Sprintf("%s/app/%s/msg", module, app),
		}

		for _, pf := range byApp[app] {
			data.LogicImports = append(data.LogicImports, fmt.Sprintf("%s/app/%s/logic/%s", module, app, pf.LogicPackage))
			data.PbImports = append(data.PbImports, struct{ Path, Package string }{pf.GoImportPath, pf.GoPackage})
			for _, m := range pf.ClientMessages() {
				data.Entries = append(data.Entries, struct{ Name, GoPackage, LogicPackage string }{
					Name: m.Name, GoPackage: pf.GoPackage, LogicPackage: pf.LogicPackage,
				})
			}
		}

		if err := writeGenerated(filepath.Join(repoRoot, "app", app, "processor_registry.gen.go"), registerTmpl, data); err != nil {
			return err
		}
	}
	return nil
}

// writeGenerated 渲染模板、gofmt 一遍、落盘。全量覆盖。
func writeGenerated(path, tmpl string, data any) error {
	buf, err := render(tmpl, data)
	if err != nil {
		return fmt.Errorf("%s: %w", path, err)
	}
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		return err
	}
	if err := os.WriteFile(path, buf, 0o644); err != nil {
		return err
	}
	log.Printf("生成 %s", path)
	return nil
}

// writeIfMissing 只在文件不存在时创建。已经有的是人写的，不能碰。
const logicStubFragmentTmpl = `{{range $msg := .}}
func Process{{$msg.Name}}(ctx context.Context, req *msg.{{$msg.Name}}) error {
	// TODO: 实现业务逻辑
	return nil
}
{{end}}`

// genLogicStub 保证每个客户端协议都有对应的 Process 函数。
//
// 文件不存在就整个建出来；已存在就在末尾补上缺的那些。两种情况下都只做加法——
// 里面是人写的业务逻辑。之所以要补而不是"文件在就跳过"，是因为协议是按 message
// 加的：文件一旦存在，之后新增的协议就永远拿不到脚手架，而生成的注册表已经
// 引用了它，编译直接断。
func genLogicStub(path string, pf *protoFile) error {
	clients := pf.ClientMessages()
	if len(clients) == 0 {
		return nil
	}

	src, err := os.ReadFile(path)
	if os.IsNotExist(err) {
		if err := writeGenerated(path, logicStubTmpl, pf); err != nil {
			return err
		}
		log.Printf("%s 是新建的脚手架，之后归人维护", path)
		return nil
	}
	if err != nil {
		return err
	}

	fset := token.NewFileSet()
	f, err := parser.ParseFile(fset, path, src, parser.SkipObjectResolution)
	if err != nil {
		return fmt.Errorf("%s 解析不了（是不是正改到一半？），改完再跑生成器: %w", path, err)
	}

	have := make(map[string]bool, len(f.Decls))
	for _, d := range f.Decls {
		if fn, ok := d.(*ast.FuncDecl); ok && fn.Recv == nil {
			have[fn.Name.Name] = true
		}
	}

	var missing []*protoMsg
	for _, m := range clients {
		if !have["Process"+m.Name] {
			missing = append(missing, m)
		}
	}
	if len(missing) == 0 {
		return nil
	}

	// 追加的 stub 要用 context 和 msg 包。文件里没有就让人自己加——生成器不猜 import，
	// 猜错了会写出一份编译不过的文件，比直接报错难查。
	for _, need := range []string{"context", pf.MsgImportPath()} {
		if !hasImport(f, need) {
			return fmt.Errorf("%s 缺 %q 的导入，补上再跑生成器", path, need)
		}
	}

	var frag bytes.Buffer
	if err := template.Must(template.New("frag").Parse(logicStubFragmentTmpl)).Execute(&frag, missing); err != nil {
		return err
	}

	// 整份过一遍 gofmt：人写的那部分本来就是格式化过的，等于没动；
	// 追加的部分则保证格式正确。过不了说明拼出来的不是合法 Go，不写。
	merged, err := format.Source(append(slices.Clone(src), frag.Bytes()...))
	if err != nil {
		return fmt.Errorf("补齐 %s 后不是合法 Go，没写入: %w", path, err)
	}
	if err := os.WriteFile(path, merged, 0o644); err != nil {
		return err
	}

	names := make([]string, 0, len(missing))
	for _, m := range missing {
		names = append(names, "Process"+m.Name)
	}
	log.Printf("补齐 %s：%s", path, strings.Join(names, ", "))
	return nil
}

func hasImport(f *ast.File, path string) bool {
	for _, imp := range f.Imports {
		if s, err := strconv.Unquote(imp.Path.Value); err == nil && s == path {
			return true
		}
	}
	return false
}

// render 渲染模板并 gofmt。生成的东西必须能编译，格式不对就直接报错。
func render(tmpl string, data any) ([]byte, error) {
	t, err := template.New("gen").Parse(tmpl)
	if err != nil {
		return nil, err
	}
	var buf bytes.Buffer
	if err := t.Execute(&buf, data); err != nil {
		return nil, err
	}
	src, err := format.Source(buf.Bytes())
	if err != nil {
		return nil, fmt.Errorf("生成的代码不合法: %w\n---\n%s", err, buf.String())
	}
	return src, nil
}
