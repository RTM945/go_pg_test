// vtFeatures 不开 pool：没有消息标 mempool，交给处理函数的消息也不该回池——函数返回后谁还拿着它说不清。
const vtFeatures = "marshal+unmarshal+size"

// plugins 是 protoc 要用的插件。它们都在 go.mod 的依赖里，版本跟着 go.mod 走（见 buildPlugins）。
var plugins = []struct{ name, pkg string }{
	{"protoc-gen-go", "google.golang.org/protobuf/cmd/protoc-gen-go"},
	{"protoc-gen-go-vtproto", "github.com/planetscale/vtprotobuf/cmd/protoc-gen-go-vtproto"},
}

func main() {
	wd, _ := os.Getwd()
	repoRoot, err := findRepoRoot(wd)
	if err != nil {
		log.Fatal("findRepoRoot:", err)
	}

	module, err := modulePath(filepath.Join(repoRoot, "go.mod"))
	if err != nil {
		log.Fatal("modulePath:", err)
	}

	// protoc 的产物（genpb/**/*.pb.go、desc.pb）由 protoc 自己写、自己覆盖，
	// 失败时它不会删旧文件，genpb 不碰它们。
	// genpb 只负责自己模板产出的部分（logic 脚手架、注册表、protocol_types.go）：
	// 这些先留在内存里，等所有生成步骤都成功了再统一落盘，
	// 生成失败时仓库里的旧代码原封不动。
	// go_pg_test/proto，所有 proto 共用的 -I 根
	protoRoot := filepath.Join(repoRoot, "proto")
	desc := filepath.Join(repoRoot, "genpb", "desc.pb")
	if err := os.MkdirAll(filepath.Dir(desc), 0o755); err != nil {
		log.Fatal("create genpb dir:", err)
	}

	protoFiles, err := collectProtoFiles(protoRoot)
	if err != nil {
		log.Fatal("collectProtoFiles:", err)
	}
	if len(protoFiles) == 0 {
		log.Fatal("No .proto files found")
	}

	log.Printf("Found %d proto files\n", len(protoFiles))
	for _, p := range protoFiles {
		log.Println(" -", p)
	}

	pluginDir, err := buildPlugins(repoRoot)
	if err != nil {
		log.Fatal("buildPlugins:", err)
	}
	err = runProtoc(repoRoot, protoRoot, module, desc, pluginDir, protoFiles)
	_ = os.RemoveAll(pluginDir) // log.Fatal 不跑 defer，所以在这里删
	if err != nil {
		log.Fatal(err)
	}

	// map<message, typeId>
	descb, err := os.ReadFile(desc)
	if err != nil {
		log.Fatal(err)
	}
	files, typeIDExtType, err := loadDescriptors(descb)
	if err != nil {
		log.Fatal("loadDescriptors:", err)
	}

	groups, err := collectTypeIds(files, typeIDExtType)
	if err != nil {
		log.Fatal("collectTypeIds:", err)
	}
	// 模板产物先收进内存，此时仓库里 genpb 自己那部分一个字节都还没动。
	var outputs []generatedFile
	for _, g := range groups {
		f, err := renderProtocolTypes(repoRoot, module, g)
		if err != nil {
			log.Fatal("renderProtocolTypes:", err)
		}
		outputs = append(outputs, f)
	}

	// app 侧：logic 脚手架、注册表
	protos, err := collectAppProtoFiles(files, module, typeIDExtType)
	if err != nil {
		log.Fatal("collectAppProtoFiles:", err)
	}
	appFiles, err := genAppCode(repoRoot, module, protos)
	if err != nil {
		log.Fatal("genAppCode:", err)
	}
	outputs = append(outputs, appFiles...)

	// 到这里生成全部成功，才删旧模板产物、写新文件。protoc 的产物不参与。
	if err := publishGenerated(repoRoot, outputs); err != nil {
		log.Fatal("publishGenerated:", err)
	}

	fmt.Printf("protoc succeeded. generated files under %s\n", filepath.Join(repoRoot, "genpb"))
}

// generatedFile 一份已经生成好、等着发布进仓库的文件。
type generatedFile struct {
	path string
	data []byte
}

// publishGenerated 在所有生成步骤都成功之后才动仓库：先删 genpb 自己的旧产物，
// 再把内存里的新内容写进去。走到这里已经不会再有 proto/模板错误，
// 剩下的只是磁盘 IO。
//
// 对比旧做法（先删再生成）：proto 写错时旧文件原封不动，
// 不会出现“旧的已删、新的没生成”、整个仓库编不过的连坐状态。
func publishGenerated(repoRoot string, files []generatedFile) error {
	if err := cleanGenerated(repoRoot); err != nil {
		return err
	}
	for _, f := range files {
		if err := os.MkdirAll(filepath.Dir(f.path), 0o755); err != nil {
			return err
		}
		if err := os.WriteFile(f.path, f.data, 0o644); err != nil {
			return err
		}
	}
	log.Printf("wrote %d generated files", len(files))
	return nil
}

// cleanGenerated 删掉 genpb 自己生成的那部分，给新产物腾位置。
//
// 只碰非 protoc 产物：
//
//	app/<app>/processor_registry.gen.go
//
// 刻意不碰的：
//
//	genpb/                            里面的 *.pb.go、*_vtproto.pb.go、desc.pb
//	                                  是 protoc 的产物，由 protoc 自己覆盖；
//	                                  genpb 删它们只会让生成失败时整个仓库编不过。
//	                                  protocol_types.go 也在这里，每次整份重写，不用先删
//	app/<app>/logic/                  msg_*.go 里是人写的业务逻辑
//	app/<app>/ptable/                 pdbgen 的产出，不是我们的地盘
//
// 只在 publishGenerated 里、所有生成都成功之后调用。
func cleanGenerated(repoRoot string) error {
	apps, err := os.ReadDir(filepath.Join(repoRoot, "app"))
	if err != nil {
		if os.IsNotExist(err) {
			return nil
		}
		return err
	}
	for _, app := range apps {
		if !app.IsDir() {
			continue
		}
		registry := filepath.Join(repoRoot, "app", app.Name(), "processor_registry.gen.go")
		if err := os.Remove(registry); err != nil && !os.IsNotExist(err) {
			return err
		}
	}
	return nil
}

// 标记必须在 package 之前——Go 的约定，go generate 一类工具靠它在文件开头认生成物，
// 我们自己的 cleanGenerated 也靠它。
const protocolTypesTmpl = `// Code generated by genpb; DO NOT EDIT.

package {{.GoPackage}}

// 每个打了 (proto.type_id) 的 message 一个协议号常量和一个 TypeId 方法。
// 加上 vtprotobuf 生成的编解码方法，这些类型本身就是 io.Msg：直接 &{{.GoPackage}}.X{...} 构造、发送。

{{range .TypeIds}}
const PROTOCOL_TYPE_{{.Name}} int32 = {{.TypeId}}

func (*{{.Name}}) TypeId() int32 { return PROTOCOL_TYPE_{{.Name}} }
{{end}}`

// renderProtocolTypes 把一个 go_package 下的协议号常量和 TypeId 方法渲染进内存。
// 每个 app 一份，互不污染——app 编译时不会链到别人的协议号。
func renderProtocolTypes(repoRoot, module string, g *typeIdGroup) (generatedFile, error) {
	rel, ok := strings.CutPrefix(g.GoImportPath, module+"/")
	if !ok {
		return generatedFile{}, fmt.Errorf("go_package %q is not under module %s", g.GoImportPath, module)
	}
	return renderFile(filepath.Join(repoRoot, filepath.FromSlash(rel), "protocol_types.go"), protocolTypesTmpl, g)
}

// modulePath 从 go.mod 里读出 module 名，别在代码里硬编码。
func modulePath(goModPath string) (string, error) {
	f, err := os.Open(goModPath)
	if err != nil {
		return "", err
	}
	defer f.Close()

	sc := bufio.NewScanner(f)
	for sc.Scan() {
		if after, ok := strings.CutPrefix(strings.TrimSpace(sc.Text()), "module "); ok {
			return strings.TrimSpace(after), nil
		}
	}
	if err := sc.Err(); err != nil {
		return "", err
	}
	return "", fmt.Errorf("%s: no module line found", goModPath)
}

// buildPlugins 在一个临时目录里按 go.mod 的版本编出 protoc 插件，返回这个目录，用完由调用方删掉。
//
// 不用 go install @latest：装到的 protoc-gen-go 可能比 go.mod 里的 protobuf 运行时新，
// 生成的代码会用到运行时还没有的东西；换一台机器，生成结果也可能不一样。
// 第二次起 go build 走构建缓存，只剩链接。
func buildPlugins(repoRoot string) (string, error) {
	dir, err := os.MkdirTemp("", "genpb-plugins-")
	if err != nil {
		return "", err
	}
	args := []string{"build", "-o", dir}
	for _, p := range plugins {
		args = append(args, p.pkg)
	}
	cmd := exec.Command("go", args...)
	cmd.Dir = repoRoot
	cmd.Stderr = os.Stderr
	if err := cmd.Run(); err != nil {
		_ = os.RemoveAll(dir)
		return "", fmt.Errorf("go build %v: %w", args[3:], err)
	}
	return dir, nil
}

// runProtoc 跑一遍 protoc：*.pb.go、*_vtproto.pb.go 落进仓库，desc.pb 留给后面的生成步骤。
func runProtoc(repoRoot, protoRoot, module, desc, pluginDir string, protoFiles []string) error {
	exe := ""
	if runtime.GOOS == "windows" {
		exe = ".exe"
	}
	args := []string{
		"-I.", // protoRoot 下为根
		"-I" + filepath.Join(repoRoot, "third_party", "protoc", "include"),
		"-I" + filepath.Join(repoRoot, "third_party", "vtprotobuf", "include"),
		"--include_imports",
		"--include_source_info",
	}
	for _, p := range plugins {
		args = append(args, fmt.Sprintf("--plugin=%s=%s", p.name, filepath.Join(pluginDir, p.name+exe)))
	}
	// 产物直接落到仓库，落哪个子目录由每个 proto 的 go_package 决定：
	// paths=import + module= 会自己剥掉 module 前缀。module= 和 paths=source_relative 互斥，不能混用。
	args = append(args,
		"--go_out="+repoRoot,
		"--go_opt=module="+module,
		"--go-vtproto_out="+repoRoot,
		"--go-vtproto_opt=module="+module,
		"--go-vtproto_opt=features="+vtFeatures,
		"--descriptor_set_out="+desc,
	)
	args = append(args, protoFiles...)

	ctx, cancel := context.WithTimeout(context.Background(), 5*time.Minute)
	defer cancel()
	var outb, errb bytes.Buffer
	cmd := exec.CommandContext(ctx, filepath.Join(repoRoot, "bin", "protoc"), args...)
	cmd.Dir = protoRoot
	cmd.Stdout = &outb
	cmd.Stderr = &errb
	if err := cmd.Run(); err != nil {
		return fmt.Errorf("*** protoc failed: %w\nSTDOUT:\n%s\nSTDERR:\n%s", err, outb.String(), errb.String())
	}
	return nil
}

func findRepoRoot(start string) (string, error) {
	dir := start
	for {
		if _, err := os.Stat(filepath.Join(dir, "go.mod")); err == nil {
			return dir, nil
		}
		parent := filepath.Dir(dir)
		if parent == dir { // 到达根了
			break
		}
		dir = parent
	}
	return "", errors.New("repo root (go.mod) not found")
}

type msg2typeId struct {
	Name   string // message 名，用来生成 PROTOCOL_TYPE_<Name>
	TypeId int32
	where  string // 声明位置，只用于报错
}

// typeIdGroup 一个 go_package 下所有带 (proto.type_id) 的 message，
// 对应要生成的一份 protocol_types.go。
type typeIdGroup struct {
	GoImportPath string // go_pg_test/genpb/test
	GoPackage    string // testpb
	TypeIds      []*msg2typeId
}

// loadDescriptors 从 desc.pb 解析文件描述符和 (proto.type_id) 扩展类型。
//
// 这里刻意不 import go_pg_test/genpb/common：那是生成物，生成器一旦依赖它，
// genpb 缺失时生成器自己就编不过，想重跑都没机会（先有鸡还是先有蛋）。
// ext.proto 已经通过 --include_imports 进了 desc.pb，扩展类型可以从描述符
// 动态构造，不需要生成的 Go 代码。
func loadDescriptors(raw []byte) (*protoregistry.Files, protoreflect.ExtensionType, error) {
	// 第一遍：还不知道扩展类型，type_id 会被当成 unknown fields 留下，
	// 但文件/消息/扩展的声明都在，足够把扩展描述符找出来。
	fds := &descriptorpb.FileDescriptorSet{}
	if err := proto.Unmarshal(raw, fds); err != nil {
		return nil, nil, err
	}
	files, err := protodesc.NewFiles(fds)
	if err != nil {
		return nil, nil, err
	}

	var extDesc protoreflect.ExtensionDescriptor
	files.RangeFiles(func(fd protoreflect.FileDescriptor) bool {
		exts := fd.Extensions()
		for i := 0; i < exts.Len(); i++ {
			ext := exts.Get(i)
			if string(ext.Name()) == "type_id" {
				extDesc = ext
				return false
			}
		}
		return true
	})
	if extDesc == nil {
		return nil, nil, errors.New("proto.type_id extension not found; check that proto/ext.proto exists")
	}
	if extDesc.Kind() != protoreflect.Int32Kind {
		return nil, nil, fmt.Errorf("proto.type_id must be int32, got %v", extDesc.Kind())
	}

	// 第二遍：用动态扩展类型当 resolver 重新解析，options 里的 type_id 才会
	// 被真正解出来，而不是留在 unknown fields 里。
	xt := dynamicpb.NewExtensionType(extDesc)
	types := new(protoregistry.Types)
	if err := types.RegisterExtension(xt); err != nil {
		return nil, nil, err
	}
	fds = &descriptorpb.FileDescriptorSet{}
	if err := (proto.UnmarshalOptions{Resolver: types}).Unmarshal(raw, fds); err != nil {
		return nil, nil, err
	}
	files, err = protodesc.NewFiles(fds)
	if err != nil {
		return nil, nil, err
	}
	return files, xt, nil
}

// hasTypeId 判断 message options 上有没有打 (proto.type_id)。
//
// 不用 proto.HasExtension：动态扩展的描述符来自 desc.pb，和生成的
// MessageOptions 描述符不是同一个实例，proto.HasExtension 会因实例不等而
// 误报 false。reflect 的 Has 只比较全名，两种来源都能用。
func hasTypeId(opts protoreflect.ProtoMessage, extType protoreflect.ExtensionType) bool {
	return opts.ProtoReflect().Has(extType.TypeDescriptor())
}

// typeIdField 找出会生成 Go 字段 TypeId 的字段或 oneof，没有就返回空串。
// protoc-gen-go 把 type_id、typeId 都转成 TypeId；这里忽略大小写和下划线来比，宁可多拦。
func typeIdField(msg protoreflect.MessageDescriptor) string {
	collides := func(name protoreflect.Name) bool {
		return strings.EqualFold(strings.ReplaceAll(string(name), "_", ""), "typeid")
	}
	fields := msg.Fields()
	for i := range fields.Len() {
		if f := fields.Get(i); collides(f.Name()) {
			return string(f.Name())
		}
	}
	oneofs := msg.Oneofs()
	for i := range oneofs.Len() {
		if o := oneofs.Get(i); collides(o.Name()) {
			return string(o.Name())
		}
	}
	return ""
}

// collectTypeIds 收集所有打了 (proto.type_id) 的 message，按 typeId 升序返回。
//
// type_id 撞车和 message 重名都是致命的，这里直接报错而不是放过去：
//   - type_id 撞车：两个协议共用一个编号，收包时永远只走其中一个，另一个的
//     常量还会被静默吞掉，全程没有任何提示。
//   - message 重名：生成的 PROTOCOL_TYPE_<Name> 会重复，编译器在生成文件里
//     报 redeclared，看不出是谁和谁撞了。
//   - 字段生成出来叫 TypeId（type_id、typeId）：和生成的 TypeId() 方法重名，
//     编译器在生成文件里报 "field and method with the same name"。
func collectTypeIds(files *protoregistry.Files, typeIDExtType protoreflect.ExtensionType) ([]*typeIdGroup, error) {
	byTypeId := make(map[int32]*msg2typeId)
	byName := make(map[string]*msg2typeId)
	byPackage := make(map[string]*typeIdGroup)
	var fail error

	files.RangeFiles(func(fd protoreflect.FileDescriptor) bool {
		// desc.pb 里带着 --include_imports 拉进来的 google/protobuf/*.proto，
		// 它们的 go_package 不符合本仓库约定，所以只在真碰到带 type_id 的
		// message 时才去解析，别的文件一律不管。
		var g *typeIdGroup

		messages := fd.Messages()
		for i := range messages.Len() {
			msg := messages.Get(i)
			opts := msg.Options()
			if opts == nil || !hasTypeId(opts, typeIDExtType) {
				continue
			}

			if g == nil {
				goImportPath, goPackage, err := goPackageOf(fd)
				if err != nil {
					fail = err
					return false
				}
				g = byPackage[goImportPath]
				if g == nil {
					g = &typeIdGroup{GoImportPath: goImportPath, GoPackage: goPackage}
					byPackage[goImportPath] = g
				}
			}

			typeId := proto.GetExtension(opts, typeIDExtType).(int32)
			name := string(msg.Name())
			where := fmt.Sprintf("%s (%s)", msg.FullName(), fd.Path())

			// type_id 全局唯一，跨 app 也不许重复
			if prev, ok := byTypeId[typeId]; ok {
				fail = fmt.Errorf("duplicate type_id %d: %s and %s", typeId, prev.where, where)
				return false
			}
			if prev, ok := byName[name]; ok {
				fail = fmt.Errorf("duplicate message name %s: %s and %s would both generate PROTOCOL_TYPE_%s", name, prev.where, where, name)
				return false
			}
			if field := typeIdField(msg); field != "" {
				fail = fmt.Errorf("%s: field %s becomes Go field TypeId, which collides with the generated TypeId() method; rename the field", where, field)
				return false
			}

			m := &msg2typeId{Name: name, TypeId: typeId, where: where}
			byTypeId[typeId] = m
			byName[name] = m
			g.TypeIds = append(g.TypeIds, m)
		}
		return true
	})
	if fail != nil {
		return nil, fail
	}

	groups := make([]*typeIdGroup, 0, len(byPackage))
	for _, g := range byPackage {
		slices.SortStableFunc(g.TypeIds, func(i, j *msg2typeId) int {
			return cmp.Compare(i.TypeId, j.TypeId)
		})
		groups = append(groups, g)
	}
	slices.SortStableFunc(groups, func(i, j *typeIdGroup) int {
		return cmp.Compare(i.GoImportPath, j.GoImportPath)
	})
	return groups, nil
}

// goPackageOf 拆出 proto 文件 go_package 里的 import 路径和包名。
// 必须写成 "go_pg_test/genpb/test;testpb" 这种带分号的形式，
// 否则 import 路径推导出来的包名不一定是我们想要的那个。
func goPackageOf(fd protoreflect.FileDescriptor) (importPath, packageName string, err error) {
	opts, ok := fd.Options().(*descriptorpb.FileOptions)
	if !ok || opts.GetGoPackage() == "" {
		return "", "", fmt.Errorf("%s: no go_package", fd.Path())
	}
	importPath, packageName, ok = strings.Cut(opts.GetGoPackage(), ";")
	if !ok || importPath == "" || packageName == "" {
		return "", "", fmt.Errorf(`%s: go_package must be "import/path;pkgname", got %q`,
			fd.Path(), opts.GetGoPackage())
	}
	return importPath, packageName, nil
}

func collectProtoFiles(root string) ([]string, error) {
	var files []string
	err := filepath.Walk(root, func(path string, info os.FileInfo, err error) error {
		if err != nil {
			return err
		}
		if info.Mode().IsRegular() && filepath.Ext(path) == ".proto" {
			rel, err := filepath.Rel(root, path) // 相对于 protoRoot 的相对路径
			if err != nil {
				return err
			}
			// 使用 Unix 风格分隔符更可靠（protoc 接受 /）
			rel = filepath.ToSlash(rel)
			files = append(files, rel)
		}
		return nil
	})
	return files, err
}
